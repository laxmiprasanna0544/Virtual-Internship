/**
 * Generates types/db.ts from the live schema.
 *
 *   npm run db:types        # after running migrations against the local database
 *
 * Reads DATABASE_URL (or .env.local). Emits one Row type per table in the
 * public schema, plus the enums, in the shape lib/records/*.ts expects.
 */
import { readFileSync, writeFileSync } from "node:fs";
import postgres from "postgres";

function loadEnv() {
  try {
    for (const line of readFileSync(new URL("../.env.local", import.meta.url), "utf8").split("\n")) {
      const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
      if (match && !(match[1] in process.env)) process.env[match[1]] = match[2];
    }
  } catch {
    // No .env.local: rely on the environment.
  }
}
loadEnv();

const sql = postgres(process.env.DATABASE_URL, { max: 1 });

const enums = await sql`
  select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t
  join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public'
  group by t.typname
  order by t.typname`;

const columns = await sql`
  select c.table_name, c.column_name, c.is_nullable = 'YES' as nullable,
         c.data_type, c.udt_name, c.column_default is not null as has_default
  from information_schema.columns c
  join information_schema.tables t
    on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
    and c.table_name <> 'schema_migrations'
  order by c.table_name, c.ordinal_position`;

const enumNames = new Set(enums.map((e) => e.name));

function tsType(col) {
  const udt = col.udt_name;
  if (udt.startsWith("_")) {
    const inner = udt.slice(1);
    return `${scalar(inner)}[]`;
  }
  return scalar(udt);
}

function scalar(udt) {
  if (enumNames.has(udt)) return `Enums["${udt}"]`;
  switch (udt) {
    case "int2":
    case "int4":
    case "float4":
    case "float8":
    case "numeric":
      return "number";
    case "int8":
      return "string";
    case "bool":
      return "boolean";
    case "json":
    case "jsonb":
      return "Json";
    default:
      return "string";
  }
}

const tables = new Map();
for (const col of columns) {
  if (!tables.has(col.table_name)) tables.set(col.table_name, []);
  tables.get(col.table_name).push(col);
}

let out = `// Generated by scripts/gen-db-types.mjs from the database schema. Do not edit.
// Regenerate with \`npm run db:types\` after changing db/migrations.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export interface Enums {
${enums.map((e) => `  ${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(" | ")};`).join("\n")}
}

export interface Tables {
`;
for (const [table, cols] of tables) {
  out += `  ${table}: {\n    Row: {\n`;
  for (const col of cols) {
    out += `      ${col.column_name}: ${tsType(col)}${col.nullable ? " | null" : ""};\n`;
  }
  out += `    };\n  };\n`;
}
out += `}\n`;

writeFileSync(new URL("../types/db.ts", import.meta.url), out);
console.log(`types/db.ts: ${tables.size} tables, ${enums.length} enums`);
await sql.end();
